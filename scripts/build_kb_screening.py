def main() -> None:
    rows = [("판정", label, text) for _, label, text in VERDICT]
    rows += [("이후절차", k, t) for k, t, _ in NEXT_STEP]
    rows += [("검사비지원", k, t) for k, t in COST]
    with io.open(D("data", "kb", "kb_screening.csv"), "w", encoding="utf-8-sig", newline="") as fp:
        w = csv.writer(fp)
        w.writerow(["category", "key", "content"])
        w.writerows(rows)

    chunks = []
    for ln in io.open(D("data", "kb", "kb_chunks.jsonl"), encoding="utf-8"):
        c = json.loads(ln)
        if c["type"] != "screening":
            chunks.append(c)

    def add(cid, text, meta, source):
        chunks.append({"id": cid, "type": "screening", "text": text, "meta": meta, "source": source})

    for key, label, text in VERDICT:
        add("scr_verdict_%s" % key,
            "영유아 건강검진 발달선별검사 판정 '%s': %s" % (label, text),
            {"kind": "verdict", "verdict": label}, LAW)
    for key, text, src in NEXT_STEP:
        add("scr_step_%s" % key, text, {"kind": "next_step"}, src)
    for key, text in COST:
        add("scr_cost_%s" % key, text, {"kind": "cost_support"}, JEONGBU)

    with io.open(D("data", "kb", "kb_chunks.jsonl"), "w", encoding="utf-8") as fp:
        for c in chunks:
            fp.write(json.dumps(c, ensure_ascii=False) + "\n")

    print("발달검사 KB 추가 완료")
    for t, n in collections.Counter(c["type"] for c in chunks).most_common():
        print("  %-24s %4d" % (t, n))
    print("  %-24s %4d" % ("합계", len(chunks)))


if __name__ == "__main__":
    main()
