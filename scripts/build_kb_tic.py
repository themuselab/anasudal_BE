def main():
    rows = []
    for k, c in DEFINITION:
        rows.append(("틱 정의·특성", k, c))
    for k, c in TIC_TYPE:
        rows.append(("틱 종류", k, c))
    for k, c in DIAGNOSIS:
        rows.append(("틱장애 진단 분류", k, c))
    for k, c in COURSE:
        rows.append(("틱 경과·역학", k, c))
    for k, c in CAUSE:
        rows.append(("틱 원인", k, c))
    for k, c in COMORBID:
        rows.append(("틱 동반질환", k, c))
    for i, c in enumerate(TREAT_CRITERIA, 1):
        rows.append(("적극적 치료가 필요한 경우", "%d" % i, c))
    for k, c, a in TREATMENT:
        rows.append(("틱 치료", k, c + ((" [대응 치료영역: " + a + "]") if a else "")))
    for k, c in FAMILY:
        rows.append(("가족 교육", k, c))

    with io.open(D("data", "kb", "kb_tic.csv"), "w", encoding="utf-8-sig", newline="") as fp:
        w = csv.writer(fp)
        w.writerow(["category", "key", "content"])
        w.writerows(rows)

    chunks = []
    for ln in io.open(D("data", "kb", "kb_chunks.jsonl"), encoding="utf-8"):
        c = json.loads(ln)
        if c["type"] != "tic":
            chunks.append(c)

    def add(cid, text, meta):
        chunks.append({"id": cid, "type": "tic", "text": text, "meta": meta, "source": SRC})

    for k, c in DEFINITION:
        add("tic_def_%s" % k[:12], "틱장애 — %s: %s" % (k, c), {"kind": "definition"})
    for k, c in TIC_TYPE:
        add("tic_ty_%s" % k, "틱 종류 '%s': %s" % (k, c), {"kind": "type"})
    for k, c in DIAGNOSIS:
        add("tic_dx_%s" % k[:14], "틱장애 진단 '%s': %s" % (k, c), {"kind": "diagnosis"})
    for k, c in COURSE:
        add("tic_co_%s" % k, "틱장애 %s: %s" % (k, c), {"kind": "course"})
    for k, c in CAUSE:
        add("tic_ca_%s" % k, "틱장애 원인 — %s: %s" % (k, c), {"kind": "cause"})
    for k, c in COMORBID:
        add("tic_cm_%s" % k, "틱장애 동반질환 '%s': %s" % (k, c), {"kind": "comorbidity"})
    for i, c in enumerate(TREAT_CRITERIA, 1):
        add("tic_crit_%d" % i, "틱장애에서 적극적인 치료가 필요한 경우: %s" % c,
            {"kind": "treatment_criteria", "severity": "action_needed"})
    for k, c, a in TREATMENT:
        add("tic_tx_%s" % k[:12], "틱장애 치료 '%s': %s%s" % (k, c, (" (대응 법정 치료영역: %s)" % a) if a else ""),
            {"kind": "treatment", "therapy_area": a})
    for k, c in FAMILY:
        add("tic_fam_%s" % k[:12], "틱장애 가족 대처 — %s: %s" % (k, c), {"kind": "family_guidance"})

    with io.open(D("data", "kb", "kb_chunks.jsonl"), "w", encoding="utf-8") as fp:
        for c in chunks:
            fp.write(json.dumps(c, ensure_ascii=False) + "\n")

    print("틱장애 KB 추가 완료 (%d항목)" % len(rows))
    for t, n in collections.Counter(c["type"] for c in chunks).most_common():
        print("  %-24s %4d" % (t, n))
    print("  %-24s %4d" % ("합계", len(chunks)))


if __name__ == "__main__":
    main()
