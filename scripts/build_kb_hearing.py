def main():
    rows = []
    for k, c in DEGREE:
        rows.append(("난청 정도", k, c))
    for k, c in SYMPTOM:
        rows.append(("난청 증상", k, c))
    for k, c in TYPE:
        rows.append(("난청 종류", k, c))
    for k, c in CAUSE:
        rows.append(("난청 원인", k, c))
    for k, c in TEST:
        rows.append(("청각 검사도구", k, c))
    for k, c in TIMELINE:
        rows.append(("조기개입 타임라인", k, c))
    for i, c in enumerate(RISK, 1):
        rows.append(("난청 고위험인자", "%d" % i, c))
    for k, c in CLINICAL:
        rows.append(("난청 임상정보", k, c))

    with io.open(D("data", "kb", "kb_hearing.csv"), "w", encoding="utf-8-sig", newline="") as fp:
        w = csv.writer(fp)
        w.writerow(["category", "key", "content"])
        w.writerows(rows)

    chunks = []
    for ln in io.open(D("data", "kb", "kb_chunks.jsonl"), encoding="utf-8"):
        c = json.loads(ln)
        if c["type"] not in ("hearing",):
            chunks.append(c)

    def add(cid, text, meta):
        chunks.append({"id": cid, "type": "hearing", "text": text, "meta": meta, "source": SRC})

    for k, c in DEGREE:
        add("hear_deg_%s" % k, "난청 정도 '%s': %s" % (k, c), {"kind": "degree"})
    for k, c in SYMPTOM:
        add("hear_sym_%s" % k, "유소아 난청 증상 (%s): %s" % (k, c), {"kind": "symptom"})
    for k, c in TYPE:
        add("hear_ty_%s" % k, "난청 종류 '%s': %s" % (k, c), {"kind": "type"})
    for k, c in CAUSE:
        add("hear_ca_%s" % k, "유소아 난청 원인 '%s': %s" % (k, c), {"kind": "cause"})
    for k, c in TEST:
        add("hear_te_%s" % k[:14], "청각 검사도구 %s: %s" % (k, c), {"kind": "assessment"})
    for k, c in TIMELINE:
        add("hear_tl_%s" % k, "난청 조기개입 타임라인 — %s: %s" % (k, c), {"kind": "timeline", "milestone": k})
    for i, c in enumerate(RISK, 1):
        add("hear_risk_%d" % i, "신생아 난청 고위험인자: %s" % c, {"kind": "risk_factor"})
    for k, c in CLINICAL:
        add("hear_cl_%s" % k, "[유소아 난청 %s] %s" % (k, c), {"kind": "clinical"})

    with io.open(D("data", "kb", "kb_chunks.jsonl"), "w", encoding="utf-8") as fp:
        for c in chunks:
            fp.write(json.dumps(c, ensure_ascii=False) + "\n")

    print("유소아 난청 KB 추가 완료 (%d항목)" % len(rows))
    for t, n in collections.Counter(c["type"] for c in chunks).most_common():
        print("  %-24s %4d" % (t, n))
    print("  %-24s %4d" % ("합계", len(chunks)))


if __name__ == "__main__":
    main()
