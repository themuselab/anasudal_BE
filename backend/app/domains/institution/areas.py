"""치료영역 검색어 사전.

DB 의 therapy_area.name 은 법정 명칭(언어재활·감각발달재활 …)인데 부모가 쓰는 말은 다르다(언어치료·감각통합).
둘러보기 검색창에서 어느 쪽으로 쳐도 같은 영역을 찾도록 별칭을 둔다.
"""

ALIASES: dict[str, tuple[str, ...]] = {
    "SPEECH":   ("언어재활", "언어치료", "언어", "말", "발음"),
    "AUDIT":    ("청능재활", "청능치료", "청능", "청각", "난청"),
    "ART":      ("미술심리재활", "미술치료", "미술", "그림"),
    "MUSIC":    ("음악재활", "음악치료", "음악"),
    "PLAY":     ("놀이심리재활", "놀이치료", "놀이"),
    "BEHAV":    ("행동발달재활", "행동치료", "행동", "aba"),
    "PSYCH":    ("재활심리", "심리치료", "심리상담"),
    "SENSORY":  ("감각발달재활", "감각통합치료", "감각통합", "감각"),
    "MOTOR":    ("운동발달재활", "운동치료", "운동", "물리치료"),
    "PSYMOTOR": ("심리운동치료", "심리운동"),
    "ETC":      ("기타",),
}


def match_area_codes(q: str) -> list[str]:
    """검색어에 해당하는 치료영역 코드. 없으면 빈 목록(= 이름 검색만 수행)."""
    s = q.strip().lower().replace(" ", "")
    if not s:
        return []
    hits = []
    for code, words in ALIASES.items():
        # 검색어가 별칭의 일부이거나("언어" → 언어치료), 별칭이 검색어에 통째로 들어있거나("언어치료센터").
        # 뒤쪽은 3글자 이상 별칭만 본다 — "운동"이 "심리운동"에 걸리는 오매칭을 막는다.
        if any(s in w or (len(w) >= 3 and w in s) for w in words):
            hits.append(code)
    return hits
